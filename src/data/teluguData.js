// Helper to generate combinations with correct Telugu Unicode rendering:
export function getGuninthamForConsonant(consonantChar, baseTranslit) {
  return GUNINTHAPU_GURTULU.map(gurtu => {
    let combinedChar = "";
    if (gurtu.sign === "") {
      combinedChar = consonantChar;
    } else {
      combinedChar = consonantChar + gurtu.sign;
    }

    const fullTranslit = baseTranslit + gurtu.translit;
    return {
      signName: gurtu.name,
      vowel: gurtu.vowel,
      signSymbol: gurtu.symbol,
      combinedChar,
      translit: fullTranslit,
      formula: `${consonantChar} + ${gurtu.sign || "అ"} = ${combinedChar}`
    };
  });
}

